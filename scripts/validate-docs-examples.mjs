#!/usr/bin/env node
/**
 * Type-check the live examples on the documentation pages.
 *
 * Four of the twenty-two component bugs reported in August 2026 were docs
 * examples written against an API that does not exist. Nothing compiled them -
 * the snippets live inside a template literal, so they are a string as far as
 * TypeScript is concerned, and the first person to find out was a reader
 * watching the page throw.
 *
 * This turns each snippet into a real .tsx module and runs tsc over the lot.
 * Three of those four are compile errors, verified by reintroducing each one:
 *
 *   Pricing given `price: '$9'` where it wants `{ monthly, yearly }`   caught
 *   Testimonials given `author` where it reads `name`                  caught
 *   LogoWall given `src` where it reads `logo`                         caught
 *   Features given `icon: 'code'` where it takes a ReactNode           NOT caught
 *
 * The last one is not catchable here and never will be: `ReactNode` includes
 * `string`, so `icon: 'code'` is a perfectly legal value that happens to render
 * the word "code" instead of an icon. That is a semantic mistake, not a type
 * error, and narrowing the prop to reject strings would also reject the
 * legitimate case of an emoji. Worth knowing what this does not cover.
 *
 * The generated module mirrors what LiveCode actually does at runtime rather
 * than what the snippet looks like:
 *
 *   - LiveCode strips every `import` line and evaluates the rest against an
 *     injected scope, so the imports are decorative for execution. They are kept
 *     anyway, under aliased names, because they are what a reader copies out -
 *     that is what catches a wrong subpath like `@jarllyng/nostromo/icon`.
 *   - The scope it injects (React, its hooks, and every package export) is
 *     declared as real bindings, so the five snippets that lean on the scope
 *     instead of importing still check.
 *
 * Types resolve through the package's `exports` map into dist, not into src. The
 * consumer smoke app made the same choice on purpose: dist is what ships, and a
 * type that only exists in src helps nobody.
 */
import { execFileSync } from "node:child_process";
import { existsSync, mkdirSync, rmSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

import { extractLiveExamples } from "./lib/extract-live-examples.mjs";

/**
 * Re-emit an import so its module specifier and named exports are still resolved,
 * under names that cannot collide with the injected scope bindings. Returns null
 * for anything unrecognised rather than emitting something that will not parse.
 */
function aliasImport(line, prefix) {
  const from = line.match(/from\s*["']([^"']+)["']/);
  if (!from) return null;
  const specifier = from[1];
  const clause = line.slice(line.indexOf("import") + 6, from.index).trim();

  // import * as Foo from "x"
  const star = clause.match(/^\*\s+as\s+([A-Za-z0-9_$]+)$/);
  if (star) return `import * as ${prefix}_${star[1]} from "${specifier}";`;

  const named = clause.match(/\{([^}]*)\}/);
  const defaultName = clause.replace(/\{[^}]*\}/, "").replace(/,/g, "").trim();

  const parts = [];
  if (defaultName) parts.push(`default as ${prefix}_d_${defaultName}`);
  if (named) {
    for (const entry of named[1].split(",")) {
      const name = entry.trim();
      if (!name) continue;
      const local = name.split(/\s+as\s+/).pop().trim();
      const exported = name.split(/\s+as\s+/)[0].trim();
      if (!/^[A-Za-z_$][A-Za-z0-9_$]*$/.test(exported)) return null;
      parts.push(`${exported} as ${prefix}_${local}`);
    }
  }
  if (parts.length === 0) return `import "${specifier}";`;
  return `import { ${parts.join(", ")} } from "${specifier}";`;
}

const repoRoot = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const contentDir = join(repoRoot, "docs", "content");
// Inside docs/ so that `@jarllyng/nostromo` resolves through its node_modules.
const outDir = join(repoRoot, "docs", ".examples-typecheck");

const examples = extractLiveExamples(contentDir, repoRoot);
if (examples.length === 0) {
  console.error("No <LiveCode> examples found - the extractor is broken, not the docs.");
  process.exit(1);
}

// Kept in step with the scope in docs/components/LiveCode.client.tsx. If that
// gains a binding and this does not, a snippet using it fails here with
// "Cannot find name" - which is the right failure: the two must agree.
const PREAMBLE = `/* Generated by scripts/validate-docs-examples.mjs - do not edit. */
/* eslint-disable */
import * as React from "react";
import * as __scope from "@jarllyng/nostromo";
declare const require: unknown;
// react-live injects render() in noInline mode; a couple of examples call it.
declare function render(node: React.ReactNode): void;
void render;
const { useState, useEffect, useRef, useCallback, useMemo } = React;
void [useState, useEffect, useRef, useCallback, useMemo];
`;
const PREAMBLE_LINES = PREAMBLE.split("\n").length - 1;

// Imported by file URL, not by package name: this script runs from the repo
// root, which does not depend on the package. Reading the names off the built
// entry rather than off src is deliberate - the scope has to match what ships.
const distEntry = join(repoRoot, "packages", "nostromo", "dist", "index.js");
if (!existsSync(distEntry)) {
  console.error(`${distEntry.replace(repoRoot + "/", "")} is missing - build the package first (pnpm --filter @jarllyng/nostromo build).`);
  process.exit(1);
}
const scopeNames = Object.keys(await import(pathToFileURL(distEntry).href))
  .filter((n) => /^[A-Za-z_$][A-Za-z0-9_$]*$/.test(n) && n !== "default");

rmSync(outDir, { recursive: true, force: true });
mkdirSync(outDir, { recursive: true });

const generated = [];
for (const example of examples) {
  const name = `${example.file.replace(/[^A-Za-z0-9]+/g, "_")}__${example.index}`;
  const importLines = [];
  const bodyLines = [];

  example.code.split("\n").forEach((line) => {
    if (/^\s*import\s/.test(line)) {
      importLines.push(line.trim());
      // Keep the line count aligned so diagnostics map back to the MDX.
      bodyLines.push("");
    } else {
      bodyLines.push(line);
    }
  });

  // Re-emit each import under aliases so the specifier and the named exports are
  // still resolved, without colliding with the injected scope bindings.
  const aliased = importLines.map((line, i) => aliasImport(line, `${name}_${i}`)).filter(Boolean);

  // Type-only specifiers have to survive under their real names. They are not in
  // the runtime scope - types do not exist at runtime, so reading the export
  // names off dist cannot see them - and aliasing them away left snippets using
  // `TableColumn` with "Cannot find name". A type and a value can share a name in
  // TypeScript, so re-importing them here cannot collide with the scope bindings.
  //
  // Detection: an explicit `type` modifier, or a specifier that is not a runtime
  // export of the package. The second rule is what catches `import { Table, type
  // TableColumn }` written without the modifier.
  const typeImports = [];
  for (const line of importLines) {
    const from = line.match(/from\s*["']([^"']+)["']/);
    const named = line.match(/\{([^}]*)\}/);
    if (!from || !named) continue;
    const isTypeOnlyLine = /^\s*import\s+type\s/.test(line);
    const wanted = [];
    for (const entry of named[1].split(",")) {
      const raw = entry.trim();
      if (!raw) continue;
      const explicit = /^type\s+/.test(raw);
      const bare = raw.replace(/^type\s+/, "").split(/\s+as\s+/)[0].trim();
      const local = raw.replace(/^type\s+/, "").split(/\s+as\s+/).pop().trim();
      if (!/^[A-Za-z_$][A-Za-z0-9_$]*$/.test(bare)) continue;
      if (explicit || isTypeOnlyLine || !scopeNames.includes(bare)) {
        wanted.push(bare === local ? bare : `${bare} as ${local}`);
      }
    }
    if (wanted.length) typeImports.push(`import type { ${wanted.join(", ")} } from "${from[1]}";`);
  }

  // Only declare the scope names the snippet actually mentions: destructuring all
  // 164 exports collides with locally declared helpers in some examples.
  const mentioned = scopeNames.filter((n) =>
    new RegExp(`(?:<|\\b)${n}\\b`).test(example.code),
  );
  const scopeDecl = mentioned.length
    ? `const { ${mentioned.join(", ")} } = __scope;\nvoid [${mentioned.join(", ")}];\n`
    : "";

  const file = join(outDir, `${name}.tsx`);
  const head = [...aliased, ...typeImports];
  writeFileSync(
    file,
    PREAMBLE + head.join("\n") + (head.length ? "\n" : "") + scopeDecl + bodyLines.join("\n"),
  );
  generated.push({
    ...example,
    generatedFile: `${name}.tsx`,
    offset: PREAMBLE_LINES + head.length + (head.length ? 1 : 0) + (scopeDecl ? scopeDecl.split("\n").length - 1 : 0),
  });
}

writeFileSync(
  join(outDir, "tsconfig.json"),
  JSON.stringify(
    {
      compilerOptions: {
        // Matches how a consumer's app would be configured, not how this repo is.
        target: "ES2022",
        lib: ["ES2022", "DOM", "DOM.Iterable"],
        jsx: "react-jsx",
        module: "ESNext",
        moduleResolution: "bundler",
        strict: true,
        // Snippets are illustrative: an unused import or variable is a style
        // question, not a broken example, and flagging it would bury the bugs
        // this exists to find.
        noUnusedLocals: false,
        noUnusedParameters: false,
        noEmit: true,
        skipLibCheck: true,
        allowSyntheticDefaultImports: true,
        esModuleInterop: true,
        types: [],
      },
      include: ["*.tsx"],
    },
    null,
    2,
  ),
);

console.log(`Type-checking ${generated.length} live examples from ${new Set(generated.map((g) => g.file)).size} pages...`);

// The local binary, not `npx tsc`: npx silently falls back to fetching from the
// registry when it cannot resolve, which in CI is a slow path that looks like a
// hang. Missing here should be a loud failure instead.
const tsc = join(repoRoot, "docs", "node_modules", ".bin", "tsc");
if (!existsSync(tsc)) {
  console.error(`${tsc.replace(repoRoot + "/", "")} is missing - run pnpm install first.`);
  process.exit(1);
}

let raw = "";
try {
  execFileSync(tsc, ["-p", join(outDir, "tsconfig.json")], {
    cwd: join(repoRoot, "docs"),
    encoding: "utf8",
    stdio: ["ignore", "pipe", "pipe"],
  });
} catch (error) {
  raw = `${error.stdout ?? ""}${error.stderr ?? ""}`;
}

if (!raw.trim()) {
  console.log(`✅ All ${generated.length} examples type-check against the published types.`);
  rmSync(outDir, { recursive: true, force: true });
  process.exit(0);
}

// Map every diagnostic back to the MDX file and line a person can actually open.
const byPage = new Map();
let unmapped = 0;
for (const line of raw.split("\n")) {
  // tsc reports paths relative to its cwd, so the generated directory prefixes
  // the filename. Match the basename.
  const m = line.match(/^(?:\S*[\\/])?([^\\/\s]+\.tsx)\((\d+),(\d+)\):\s*(.*)$/);
  if (!m) continue;
  const [, file, lineNo, col, message] = m;
  const g = generated.find((x) => x.generatedFile === file);
  if (!g) {
    unmapped++;
    continue;
  }
  const mdxLine = g.line + Number(lineNo) - g.offset;
  const key = g.file;
  if (!byPage.has(key)) byPage.set(key, []);
  byPage.get(key).push({ snippet: g.index, mdxLine, col: Number(col), message });
}

console.error(`\n❌ ${[...byPage.values()].reduce((n, v) => n + v.length, 0)} type errors in docs examples\n`);
for (const [page, errors] of [...byPage].sort()) {
  console.error(`  ${page}`);
  for (const e of errors) {
    console.error(`    example #${e.snippet}, around line ${e.mdxLine}: ${e.message}`);
  }
  console.error("");
}
if (unmapped) console.error(`  (${unmapped} diagnostics could not be mapped back to a page)`);
console.error(`Generated modules left in ${outDir.replace(repoRoot + "/", "")} for inspection.`);
process.exit(1);
